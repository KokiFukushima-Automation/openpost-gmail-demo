function appendEnvLines(envPath: string, lines: string[]): void {
  const existing = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
  if (existing.length > 0) {
    copyFileSync(envPath, `${envPath}.bak.${Date.now()}`);
  }
  const separator = existing.length > 0 && !existing.endsWith('\n') ? '\n' : '';
  writeFileSync(envPath, `${existing}${separator}${lines.join('\n')}\n`, { mode: 0o600 });
  chmodSync(envPath, 0o600);
}

function buildFakePushTestEvent(trigger: NotifyTrigger): TrackingEvent {
  const now = Date.now();
  return {
    kind: trigger === 'reminder' ? 'reminder' : 'open',
    eventId: newId(),
    occurredAt: now,
    messageId: newId(),
    subject: 'Test push from `openpost push test`',
    recipientId: newId(),
    recipientEmail: 'test@example.com',
    classification: 'human',
    reasons: ['R9'],
    counted: true,
    backfilled: false,
    prevState: 'not_opened',
    newState: 'read_confirmed',
    counters: { openCount: 1, machineOpenCount: 0, clickCount: 0, firstOpenAt: now, lastOpenAt: now },
    uaFamily: 'Chrome',
    deviceType: 'desktop',
    linkUrl: null,
    muted: false,
    sentAt: now - 60_000,
    country: null,
    isAggregate: false,
    recipientCount: 0,
    campaignId: null,
  };
}

export function registerPushCommand(program: Command): void {
  const push = program.command('push').description('Web Push (VAPID) key management and device administration');

  push
    .command('keys')
    .description('Generate a VAPID key pair')
    .option('--write-env', 'append VAPID_PUBLIC_KEY/VAPID_PRIVATE_KEY/VAPID_SUBJECT to .env (0600, backed up)')
    .action((opts: { writeEnv?: boolean }, command: Command) => {
      const g = command.optsWithGlobals() as GlobalOpts;
      try {
        const keys = generateVapidKeys();
        if (opts.writeEnv) {
          const envPath = join(process.cwd(), '.env');
          if (!existsSync(envPath)) {
            throw new Error('.env does not exist yet - run `openpost init` first');
          }
          const config = loadConfig(process.env, { requireSecret: false });
          const subject = config.fromEmail ? `mailto:${config.fromEmail}` : 'mailto:openpost@localhost';
          appendEnvLines(envPath, [
            '# Generated by `openpost push keys --write-env`',
            `VAPID_PUBLIC_KEY=${keys.publicKey}`,
            `VAPID_PRIVATE_KEY=${keys.privateKey}`,
            `VAPID_SUBJECT=${subject}`,
          ]);
        }
        if (g.json) {
          // --json always includes the private key (it is the machine-readable form a script
          // would capture into its own secret store); human mode (below) never prints it.
          process.stdout.write(`${JSON.stringify(keys)}\n`);
        } else {
          process.stdout.write(`VAPID_PUBLIC_KEY=${keys.publicKey}\n`);
          if (opts.writeEnv) {
            process.stdout.write('VAPID_PRIVATE_KEY written to .env (not printed here)\n');
            process.stdout.write('Wrote VAPID_PUBLIC_KEY/VAPID_PRIVATE_KEY/VAPID_SUBJECT to .env (mode 600, backed up)\n');
          } else {
            // Human mode never prints the private key to the terminal by default - test 433.
            process.stdout.write('(private key not printed - pass --json to see it, or --write-env to store it)\n');
          }
        }
      } catch (err) {
        fail(err, g.json);
      }
    });

  push
    .command('list')
    .description('List registered push devices')
    .action((_opts: unknown, command: Command) => {
      const g = command.optsWithGlobals() as GlobalOpts;
      try {
        const config = loadConfig(process.env, { requireSecret: false });
        const db = openDb(g.db ?? config.dbPath);
        migrate(db);
        const rows = listAllSubscriptions(db);
        db.close();
        if (g.json) {
          process.stdout.write(`${JSON.stringify(rows)}\n`);
        } else {
          if (rows.length === 0) {
            process.stdout.write('no devices registered\n');
          }
          for (const r of rows) {
            const state = r.disabled_at !== null ? `disabled (${r.disabled_reason ?? 'unknown'})` : 'active';
            process.stdout.write(`${r.id}  ${r.label ?? r.ua_family ?? '(unlabelled)'}  ${state}  failures=${r.failure_count}\n`);
          }
        }
      } catch (err) {
        fail(err, g.json);
      }
    });

  push
    .command('test')
    .description('Enqueue a synthetic push notification to one/all devices right now')
    .option('--id <id>', 'target a single subscription id (default: all active)')
    .option('--trigger <trigger>', 'first_open | read_confirmed | click | reminder', 'read_confirmed')
    .action(async (opts: { id?: string; trigger?: string }, command: Command) => {
      const g = command.optsWithGlobals() as GlobalOpts;
      try {
        const config = loadConfig(process.env, { requireSecret: false });
        if (config.vapidPublicKey === undefined || config.vapidPrivateKey === undefined) {
          throw new Error('VAPID_PUBLIC_KEY/VAPID_PRIVATE_KEY are not set - run `openpost push keys --write-env` first');
        }
        const db = openDb(g.db ?? config.dbPath);
        migrate(db);
        const trigger = (opts.trigger ?? 'read_confirmed') as NotifyTrigger;
        const event = buildFakePushTestEvent(trigger);
        const payload = buildPayload(event, trigger, newId(), config);

        if (opts.id) {
          // Deliver to exactly this one device - the notifier itself always fans out over every
          // active subscription, so a single-device test bypasses it and posts directly.
          const row = getSubscription(db, opts.id);
          if (!row) throw new Error(`no subscription with id ${opts.id}`);
          const json = buildPushPayload(payload, config);
          const body = encryptPush({ plaintext: Buffer.from(JSON.stringify(json), 'utf8'), sub: { endpoint: row.endpoint, p256dh: row.p256dh, auth: row.auth } });
          const authorization = vapidAuthorization({
            endpoint: row.endpoint,
            subject: config.vapidSubject,
            keys: { publicKey: config.vapidPublicKey as string, privateKey: config.vapidPrivateKey as string },
            nowSec: Math.floor(Date.now() / 1000),
          });
          const res = await fetch(row.endpoint, {
            method: 'POST',
            headers: { TTL: String(config.pushTtlSeconds), 'Content-Encoding': 'aes128gcm', 'Content-Type': 'application/octet-stream', Authorization: authorization },
            body,
          });
          if (res.ok) {
            markSubscriptionOk(db, row.id, Date.now());
          } else {
            recordSubscriptionFailure(db, row.id, `HTTP ${res.status}`, Date.now(), config.pushMaxFailures);
          }
          db.close();
          const result = { ok: res.ok, status: res.status };
          if (g.json) process.stdout.write(`${JSON.stringify(result)}\n`);
          else process.stdout.write(result.ok ? 'OK\n' : `FAILED: HTTP ${res.status}\n`);
          return;
        }

        const result = await webpushNotifier.deliver(payload, {
          fetch: fetch as unknown as Parameters<typeof webpushNotifier.deliver>[1]['fetch'],
          timeoutMs: config.notifyTimeoutMs,
          clock: () => Date.now(),
          config,
          db,
        });
        db.close();
        if (g.json) {
          process.stdout.write(`${JSON.stringify(result)}\n`);
        } else {
          process.stdout.write(result.ok ? 'OK\n' : `FAILED: ${result.error ?? 'unknown error'}\n`);
        }
      } catch (err) {
        fail(err, g.json);
      }
    });

  push
    .command('prune')
    .description('Delete disabled push subscriptions')
    .option('--disabled-only', 'no-op (kept for symmetry - this command only ever deletes disabled subscriptions)')
    .option('--yes', 'skip the confirmation (required in non-interactive use)')
    .action((opts: { disabledOnly?: boolean; yes?: boolean }, command: Command) => {
      const g = command.optsWithGlobals() as GlobalOpts;
      try {
        if (!opts.yes) {
          throw new Error('pass --yes to confirm deleting disabled push subscriptions');
        }
        const config = loadConfig(process.env, { requireSecret: false });
        const db = openDb(g.db ?? config.dbPath);
        migrate(db);
        const deleted = pruneDisabledSubscriptions(db, Date.now());
        db.close();
        if (g.json) {
          process.stdout.write(`${JSON.stringify({ deleted })}\n`);
        } else {
          process.stdout.write(`deleted ${deleted} disabled push subscriptions\n`);
        }
      } catch (err) {
        fail(err, g.json);
      }
    });
}
